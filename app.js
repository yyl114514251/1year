  // Toast
  let toastTimer = null;
  function showToast(msg) {
    const toast = $("toast");
    toast.textContent = msg;
    toast.classList.add("show");
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => toast.classList.remove("show"), 2500);
  }

  // 生成规划
  function generatePlan() {
    currentProfile = readProfile();
    pathResults = computeScores(currentProfile);
    selectedPathIndex = 0;

    // 保存到localStorage
    try {
      localStorage.setItem("lanben_profile", JSON.stringify(currentProfile));
    } catch (e) {}

    renderPaths();
    renderPlan();
    renderAdvice();

    // 切换到路径评估tab
    document.querySelectorAll(".tab").forEach(t => t.classList.remove("active"));
    document.querySelectorAll(".tab-content").forEach(c => c.classList.remove("active"));
    document.querySelector('.tab[data-tab="paths"]').classList.add("active");
    $("tab-paths").classList.add("active");

    showToast(`✨ 规划生成完成！推荐方向：${pathResults[0].name}（${pathResults[0].composite}分）`);
  }

  // 重置
  function resetAll() {
    if (confirm("确定重置所有数据？这将清除你的画像和规划结果。")) {
      localStorage.removeItem("lanben_profile");
      currentProfile = null;
      pathResults = [];
      selectedPathIndex = 0;
      renderPaths();
      renderPlan();
      renderAdvice();
      showToast("已重置");
    }
  }

  // 恢复画像
  function restoreProfile() {
    try {
      const saved = localStorage.getItem("lanben_profile");
      if (saved) {
        const p = JSON.parse(saved);
        $("pMajor").value = p.major || "软件工程";
        $("pGrade").value = p.grade || "sophomore";
        $("pSchool").value = p.school || "211";
        $("pGpa").value = p.gpa || "top15";
        $("pFinance").value = p.finance || "middle";
        $("pRisk").value = p.risk || "balanced";
        // 恢复chips
        ["goalChips", "interestChips", "constraintChips"].forEach(id => {
          const key = id.replace("Chips", "s").replace("goal", "goals").replace("interest", "interests").replace("constraint", "constraints");
          const selected = p[key] || [];
          document.querySelectorAll(`#${id} .chip`).forEach(chip => {
            if (selected.includes(chip.dataset.value)) chip.classList.add("selected");
          });
        });
        return true;
      }
    } catch (e) {}
    return false;
  }

  // ============================================================
  // 十、初始化
  // ============================================================
  function init() {
    initTabs();
    initChips();
    renderEnvironment();
    renderPaths();
    renderPlan();
    renderAdvice();

    $("analyzeBtn").addEventListener("click", generatePlan);
    $("resetBtn").addEventListener("click", resetAll);

    // 恢复保存的画像
    if (restoreProfile()) {
      // 自动生成一次
      generatePlan();
    }
  }

  init();
