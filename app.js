  function computeScores(profile) {
    const results = PATHS.map(path => {
      const score = { ...path.base };

      // 成绩排名影响
      const gpaMod = {
        top5:   { grad: { success: 2, ceiling: 1 }, abroad: { success: 2 }, work: { income: 1 } },
        top15:  { grad: { success: 1 }, abroad: { success: 1 } },
        top30:  {},
        top50:  { grad: { success: -1 }, abroad: { success: -1 } },
        bottom: { grad: { success: -2 }, abroad: { success: -2 }, work: { success: -1 } },
      };
      const gpa = gpaMod[profile.gpa]?.[path.key] || {};
      for (const [dim, val] of Object.entries(gpa)) score[dim] = clamp(score[dim] + val, 0, 10);

      // 年级影响
      if (profile.grade === "senior") {
        score.success = clamp(score.success - 1, 0, 10);
        if (path.key === "grad") score.timeEff = clamp(score.timeEff - 1, 0, 10);
        if (path.key === "abroad") score.timeEff = clamp(score.timeEff - 1, 0, 10);
      }
      if (profile.grade === "freshman") {
        score.timeEff = clamp(score.timeEff + 1, 0, 10);
      }

      // 家庭经济影响
      if (profile.finance === "poor" || profile.finance === "ordinary") {
        if (path.key === "abroad") {
          score.ecoFriendly = clamp(score.ecoFriendly - 3, 0, 10);
          score.success = clamp(score.success - 1, 0, 10);
        }
        if (path.key === "startup") {
          score.ecoFriendly = clamp(score.ecoFriendly - 1, 0, 10);
          score.risk = clamp(score.risk - 1, 0, 10);
        }
        if (path.key === "civil") {
          score.ecoFriendly = clamp(score.ecoFriendly + 1, 0, 10);
        }
      }
      if (profile.finance === "wealthy") {
        if (path.key === "abroad") score.ecoFriendly = clamp(score.ecoFriendly + 3, 0, 10);
        if (path.key === "startup") score.risk = clamp(score.risk + 1, 0, 10);
      }

      // 风险偏好影响
      if (profile.risk === "aggressive") {
        if (path.key === "startup") { score.risk += 2; score.ceiling += 1; }
        if (path.key === "civil") { score.interest -= 1; }
      }
      if (profile.risk === "conservative") {
        if (path.key === "startup") { score.risk -= 2; score.interest -= 1; }
        if (path.key === "civil") { score.interest += 1; score.risk += 1; }
        if (path.key === "grad") { score.risk += 1; }
      }

      // 兴趣匹配（动态）
      const interestBoost = {
        ai:       { work: 2, grad: 2, startup: 1 },
        frontend: { work: 2, startup: 1 },
        backend:  { work: 2, grad: 1 },
        security: { work: 2, civil: 1, grad: 1 },
        data:     { work: 1, grad: 2, abroad: 1 },
        product:  { work: 1, startup: 2 },
        research: { grad: 3, abroad: 2 },
        hardware: { work: 1, grad: 1 },
      };
      let interestScore = 4;
      const interests = profile.interests || [];
      for (const interest of interests) {
        interestScore += (interestBoost[interest]?.[path.key] || 0) / Math.max(1, interests.length * 0.5);
      }
      score.interest = clamp(interestScore, 0, 10);

      // 核心目标决定权重
      const goalWeights = {
        money:      { income: 2, ceiling: 1.5 },
        stable:     { stability: 2, risk: 1.5 },
        academic:   { ceiling: 1.5, socialValue: 1, interest: 1 },
        impact:     { socialValue: 2, ceiling: 1 },
        freedom:    { timeEff: 1.5, interest: 1.5 },
        growth:     { ceiling: 1.5, timeEff: 1, interest: 1 },
      };
      const weights = {};
      DIMENSIONS.forEach(d => weights[d.key] = 1);
      const goals = profile.goals || [];
      goals.forEach((goal, idx) => {
        const mod = goalWeights[goal] || {};
        const priority = goals.length - idx; // 第一个目标权重最高
        for (const [dim, val] of Object.entries(mod)) {
          weights[dim] = (weights[dim] || 1) + val * priority / goals.length;
        }
      });

      // 特殊约束
      const constraints = profile.constraints || [];
      if (constraints.includes("hometown")) {
        if (path.key === "abroad") score.success -= 2;
        if (path.key === "work") { score.income -= 1; score.ceiling -= 1; }
        if (path.key === "civil") score.interest += 1;
      }
      if (constraints.includes("nodelay")) {
        if (path.key === "grad") score.timeEff -= 2;
        if (path.key === "abroad") score.timeEff -= 1;
      }
      if (constraints.includes("no996")) {
        if (path.key === "work") score.interest -= 1;
        if (path.key === "civil") score.interest += 1;
        if (path.key === "startup") score.interest -= 1;
      }

      // 计算综合得分
      let totalWeight = 0;
      let weightedSum = 0;
      for (const dim of DIMENSIONS) {
        const w = weights[dim.key] || 1;
        totalWeight += w;
        weightedSum += w * (score[dim.key] || 0);
      }
      const composite = Math.round(weightedSum / totalWeight / 10 * 100);

      // 归一化各维度分数
      const normalized = {};
      for (const dim of DIMENSIONS) {
        normalized[dim.key] = Math.round(clamp(score[dim.key] || 0, 0, 10));
      }

      return { ...path, scores: normalized, composite, weights };
    });

    results.sort((a, b) => b.composite - a.composite);
    return results;
  }

